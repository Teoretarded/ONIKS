/* Builds game/src/data/layout_ddg.js from the blast bench's DDG-51 structure (game/concepts/blast/burke_structure.js):
   the compartments (boxes in the game model frame, volumes, names, US Navy style numbers), the boundaries between each
   pair of spaces (area, plating, kind: shell / deck / bulkhead / enclosure / girder / house) and a half-breadth table
   of the hull. Run in a page (the structure takes ~0.6 s to build):

     const g = await import('/game/src/data/gen/layout_ddg_gen.js'); const src = g.source();   // the module text

   Model frame: +X starboard, +Y up, +Z bow (model = [z, y, x] of the bench's ship frame). */
import BURKE, { COMPS, PANELS, halfBreadth, deckY, keelY } from '../../../concepts/blast/burke_structure.js';

const r2 = v => Math.round(v * 100) / 100;
const r1 = v => Math.round(v * 10) / 10;

export function build() {
  const AIR = COMPS.findIndex(c => c.id === 'AIR'), SEA = COMPS.findIndex(c => c.id === 'SEA'), DOME = COMPS.findIndex(c => c.id === 'DOME');
  const keep = COMPS.filter(c => c.kind !== 'outside' && c.kind !== 'flooded' && c.vol > .5 && c.box);
  const idx = new Map(keep.map((c, i) => [c.idx, i]));
  const out = (k) => k === AIR ? -2 : (k === SEA || k === DOME) ? -1 : idx.has(k) ? idx.get(k) : null;
  const comps = keep.map(c => {
    const b = c.box;
    return [c.id, c.name, c.navy || '', c.kind === 'hull' ? (c.tank ? 'tank' : 'hull') : c.kind, r1(c.vol),
      r2(b.z[0]), r2(b.y[0]), r2(b.x[0]), r2(b.z[1]), r2(b.y[1]), r2(b.x[1])];
  });
  // boundaries: every panel between two kept spaces (or a kept space and the outside), summed per pair and kind
  const B = new Map();
  for (const pn of PANELS) {
    if (pn.kind === 'appendage') continue;
    const a = out(pn.sides[0]), b = out(pn.sides[1]);
    if (a === null || b === null || a === b || (a < 0 && b < 0)) continue;
    const lo = Math.max(a, b), hi = Math.min(a, b);            // lo: a kept space; hi: the other (or the outside, < 0)
    const kind = pn.kind === 'dome' ? 'shell' : pn.kind;
    const key = lo + ',' + hi + ',' + kind;
    let e = B.get(key);
    if (!e) B.set(key, e = { a: lo, b: hi, kind, A: 0, tA: 0, open: 0, door: 0, ax: pn.ax, bb: [1e9, 1e9, 1e9, -1e9, -1e9, -1e9] });
    const A = pn.area;
    if (pn.open) { e.open += A; continue; }
    if (pn.door) e.door += A;
    e.A += A; e.tA += A * pn.t;
    if (e.ax !== pn.ax) e.ax = -1;
    const pts = pn.poly || pn.strip[0].concat(pn.strip[1]);
    for (const p of pts) {                                     // ship [x y z] -> model [z y x]
      const m = [p[2], p[1], p[0]];
      for (let k = 0; k < 3; k++) { if (m[k] < e.bb[k]) e.bb[k] = m[k]; if (m[k] > e.bb[k + 3]) e.bb[k + 3] = m[k]; }
    }
  }
  const AXM = [2, 1, 0];                                       // ship axis -> model axis
  const bnds = [...B.values()].filter(e => e.A + e.open > .05).map(e => [e.a, e.b, e.kind, r1(e.A), r1(e.A > 0 ? e.tA / e.A : 0), e.ax < 0 ? -1 : AXM[e.ax],
    ...e.bb.map(r2), r1(e.open), r1(e.door)]);
  // the hull: half-breadth (m) at model z every 2 m, y every 1 m (-9 .. 11); the deck edge and keel per station
  const Z0 = -78, NZ = 79, Y0 = -9, NY = 21;
  const hb = [], deck = [], keel = [];
  for (let i = 0; i < NZ; i++) {
    const x = Z0 + 2 * i;
    deck.push(r2(x > 77.6 || x < -77.6 ? 0 : deckY(Math.max(-77.6, Math.min(77.6, x)))));
    keel.push(r2(x > 77.6 || x < -77.6 ? 0 : keelY(Math.max(-77.6, Math.min(77.6, x)))));
    for (let j = 0; j < NY; j++) hb.push(r2(Math.max(0, halfBreadth(x, Y0 + j))));
  }
  return { comps, bnds, hull: { z0: Z0, dz: 2, nz: NZ, y0: Y0, dy: 1, ny: NY, hb, deck, keel }, meta: BURKE.META, stats: BURKE.STATS };
}

export function source() {
  const d = build();
  const J = v => JSON.stringify(v);
  const L = [];
  L.push('/* DDG-51 Flight IIA subdivision for the game (sim/ship.js): generated by data/gen/layout_ddg_gen.js from the blast');
  L.push('   bench\'s structure (game/concepts/blast/burke_structure.js, BURKE.md). Do not edit by hand: regenerate.');
  L.push('   Model frame: +X starboard, +Y up (0 = design waterline), +Z bow; metres.');
  L.push('   comps: [id, name, number, kind (hull | tank | enclosure | house), volume m3, x0, y0, z0, x1, y1, z1 (bounding box)]');
  L.push('   bnds:  [a, b (a space, or -1 the sea, -2 the air), kind (shell | deck | bulkhead | enclosure | girder | house), area m2,');
  L.push('           plating mm (area mean), axis (0 x, 1 y, 2 z, -1 mixed), x0, y0, z0, x1, y1, z1, open m2 (uptakes), doors m2 (hangar)]');
  L.push('   hull: half-breadth at z = z0 + i dz, y = y0 + j dy: hb[i * ny + j]; deck edge and keel height per station */');
  L.push(`export const DDG_META = ${J({ name: d.meta.name, loa: d.meta.loa, lwl: d.meta.lwl, beamWL: d.meta.beamWL, depth: d.meta.depth, draught: d.meta.draughtHull, displacement_t: d.stats.displacement_t, enclosed_m3: d.stats.enclosedVolume })};`);
  L.push('export const DDG_COMPS = [');
  for (const c of d.comps) L.push('  ' + J(c) + ',');
  L.push('];');
  L.push('export const DDG_BNDS = [');
  for (let i = 0; i < d.bnds.length; i += 2) L.push('  ' + d.bnds.slice(i, i + 2).map(J).join(', ') + ',');
  L.push('];');
  const H = d.hull;
  L.push(`export const DDG_HULL = { z0: ${H.z0}, dz: ${H.dz}, nz: ${H.nz}, y0: ${H.y0}, dy: ${H.dy}, ny: ${H.ny},`);
  L.push(`  deck: ${J(H.deck)},`);
  L.push(`  keel: ${J(H.keel)},`);
  L.push('  hb: [');
  for (let i = 0; i < H.nz; i++) L.push('    ' + H.hb.slice(i * H.ny, (i + 1) * H.ny).join(',') + ',');
  L.push('  ] };');
  return L.join('\n') + '\n';
}
